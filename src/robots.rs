// Live robot state for the current room (C `robotThis[8]`). Private to this
// module; the C `curRobot` cursor has no equivalent — handlers receive their
// robot as a parameter instead.
static mut ROBOT_THIS: [Robot; 8] = [NOROBOT; 8];

// --- Movement handlers ------------------------------------------------------
// Horizontal walkers animate through fIndex 0..=3 (facing left) or 4..=7
// (facing right) and step one tile per completed cycle, bouncing between
// min and max by swapping their own do_move pointer.

fn do_move_left(robot: &mut Robot) {
    if robot.f_index > 0 {
        robot.f_index -= 1;
    } else if robot.pos > robot.min {
        robot.pos -= 8;
        robot.f_index = 3;
    } else {
        robot.do_move = do_move_right;
        robot.f_index += 4;
    }
}

fn do_move_right(robot: &mut Robot) {
    if robot.f_index < 7 {
        robot.f_index += 1;
    } else if robot.pos < robot.max {
        robot.pos += 8;
        robot.f_index = 4;
    } else {
        robot.do_move = do_move_left;
        robot.f_index &= 3;
    }
}

fn do_move_up(robot: &mut Robot) {
    robot.f_update ^= 1;
    if robot.f_update != 0 {
        robot.f_index += 1;
    }

    robot.pos -= robot.speed * WIDTH;
    if robot.pos <= robot.min {
        robot.pos = robot.min;
        robot.do_move = do_move_down;
    }
}

fn do_move_down(robot: &mut Robot) {
    robot.f_update ^= 1;
    if robot.f_update != 0 {
        robot.f_index += 1;
    }

    robot.pos += robot.speed * WIDTH;
    if robot.pos >= robot.max {
        // NB: unlike do_move_up, C does not clamp pos to max here.
        robot.do_move = do_move_up;
    }
}

fn do_move_static(robot: &mut Robot) {
    // all static sprites only alternate between 2 frames
    // i.e. 0 & 1 or 2 & 3
    robot.f_update ^= 1;
    if robot.f_update != 0 {
        robot.f_index ^= 1;
    }
}

// The arrows repurpose the fields: `max` counts down/up a 256-column cycle,
// `min` is the derived pixel offset, and `speed` holds the arrow direction
// passed to Video_DrawArrow.

fn do_move_arrow_left(robot: &mut Robot) {
    robot.max -= 1;
    if robot.max == 44 {
        unsafe {
            audioPanX = 256;
        }
        Audio_Sfx(SFX_ARROW);
    }

    if robot.max < 0 {
        robot.max = 255;
    }

    robot.min = robot.max * 8;
}

fn do_move_arrow_right(robot: &mut Robot) {
    robot.max += 1;
    if robot.max == 244 {
        unsafe {
            audioPanX = 0;
        }
        Audio_Sfx(SFX_ARROW);
    }

    if robot.max > 255 {
        robot.max = 0;
    }

    robot.min = robot.max * 8;
}

fn do_move_maria(robot: &mut Robot) {
    // Maria reacts to Willy: reads the live C globals mid-frame (see the
    // module header — no GAME_STATE, no sync).
    unsafe {
        if c_miner_willy.y < 96 && c_miner_willy.air == 0 {
            robot.f_index = 3;
        } else if c_miner_willy.y < 104 && c_miner_willy.air == 0 {
            robot.f_index = 2;
        } else {
            robot.f_index = (c_game_clock_ticks & 2) >> 1;
        }
    }
}

// --- Draw handlers -----------------------------------------------------------

fn do_draw_robot(robot: &Robot) {
    // C would dereference a null gfx here; a data-table bug, so fail loudly.
    let gfx = robot.gfx.expect("do_draw_robot: robot has no gfx");
    Video_DrawRobot(
        robot.pos,
        gfx[(robot.f_index & robot.f_mask) as usize].as_ptr(),
        robot.ink,
    );
}

fn do_draw_toilet(robot: &Robot) {
    let gfx = robot.gfx.expect("do_draw_toilet: robot has no gfx");
    Video_DrawSprite(
        robot.pos,
        gfx[(robot.f_index & robot.f_mask) as usize].as_ptr(),
        0x0,
        0x7,
    );
}

fn do_draw_arrow(robot: &Robot) {
    if robot.max < 32 {
        Video_DrawArrow(robot.pos + robot.min, robot.speed);
    }
}

// --- C-ABI entry points (called from game.c / game.rs / title.rs) ------------

#[unsafe(no_mangle)]
pub extern "C" fn Robots_Ticker() {
    unsafe {
        for robot in &mut *(&raw mut ROBOT_THIS) {
            let do_move = robot.do_move;
            do_move(robot);
        }
    }
}

#[unsafe(no_mangle)]
pub extern "C" fn Robots_Drawer() {
    unsafe {
        for robot in &*(&raw const ROBOT_THIS) {
            (robot.do_draw)(robot);
        }
    }
}

#[unsafe(no_mangle)]
pub extern "C" fn Robots_Init() {
    unsafe {
        let robots = &mut *(&raw mut ROBOT_THIS);
        *robots = ROBOT_START[c_game_level as usize];

        // Once Maria has been dealt with, the Master Bedroom robots (her two
        // colour layers) are gone.
        if c_game_level == MASTERBEDROOM && c_game_mode == GameMode::Maria as i32 {
            for robot in &mut robots[..2] {
                robot.do_move = do_move_nothing;
                robot.do_draw = do_draw_nothing;
            }
        }
    }
}

#[unsafe(no_mangle)]
pub extern "C" fn Robots_Flush() {
    // The Bathroom's toilet (slot 1) switches to its running frames (2 & 3).
    unsafe {
        let robots = &mut *(&raw mut ROBOT_THIS);
        robots[1].f_mask = 0b011;
        robots[1].f_index = 2;
        robots[1].f_update = 0; // slow down the animation
    }
}

#[unsafe(no_mangle)]
pub extern "C" fn Robots_DrawCheat() {
    // Maria's two colour layers, drawn next to the lives in the status area.
    Video_DrawRobot(LIVES as i32 + WIDTH - 24, ROBOT_GFX[43][0].as_ptr(), 0x7);
    Video_DrawRobot(LIVES as i32 + WIDTH - 24, ROBOT_GFX[44][0].as_ptr(), 0x5);
}
